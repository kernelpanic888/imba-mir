function normalizeRoadTerminology(value: string): string {
  return value
    .replaceAll("зелёным кирпичом", "шагом по зелёной дороге")
    .replaceAll("Зелёным кирпичом", "Шагом по зелёной дороге")
    .replaceAll("зелёный кирпич", "шаг по зелёной дороге")
    .replaceAll("Зелёный кирпич", "Шаг по зелёной дороге")
    .replaceAll("следующий кирпич", "следующий шаг по дороге")
    .replaceAll("Следующий кирпич", "Следующий шаг по дороге")
    .replaceAll("Ложный кирпич", "Ложный шаг")
    .replaceAll("ложный кирпич", "ложный шаг")
    .replaceAll("КИРПИЧИ", "ШАГИ ПО ДОРОГЕ")
    .replaceAll("Кирпичи", "Шаги по дороге")
    .replaceAll("кирпичей", "шагов")
    .replaceAll("кирпича", "шага")
    .replaceAll("кирпичом", "шагом по дороге")
    .replaceAll("КИРПИЧ", "ШАГ ПО ДОРОГЕ")
    .replaceAll("Кирпич", "Шаг по дороге")
    .replaceAll("кирпич", "шаг по дороге")
    .replace(/\bBRICKS\b/g, "ROAD STEPS")
    .replace(/\bBricks\b/g, "Road Steps")
    .replace(/\bbricks\b/g, "road steps")
    .replace(/\bBRICK\b/g, "ROAD STEP")
    .replace(/\bBrick\b/g, "Road Step")
    .replace(/\bbrick\b/g, "road step");
}

function translateCore(value: string): string {
  const direct = EN[value];
  if (direct) return direct;
  for (const [pattern, replacement] of DYNAMIC) {
    if (!pattern.test(value)) continue;
    pattern.lastIndex = 0;
    return typeof replacement === "string" ? value.replace(pattern, replacement) : value.replace(pattern, replacement as (...args: string[]) => string);
  }
  return value;
}

export function translateText(locale: Locale, value: string): string {
  const normalized = normalizeRoadTerminology(value);
  if (locale === "ru" || !/[А-Яа-яЁё]/u.test(normalized)) return normalized;
  const match = normalized.match(/^(\s*)([\s\S]*?)(\s*)$/u);
  if (!match) return translateCore(normalized);
  const [, before, core, after] = match;
  const direct = translateCore(core);
  if (direct !== core) return `${before}${direct}${after}`;

  // React may split a sentence around an interpolated value. Translate only
  // stable, semantically unambiguous fragments here; never translate IDs.
  const fragments: Array<[string, string]> = [
    ["ГЛАВА ", "CHAPTER "], [" · ГЛАВА ", " · CHAPTER "],
    ["проявлена из Тени на тике ", "manifested from Shadow on tick "],
    ["ИЗ ЗАМКА / ", "FROM THE CASTLE / "], ["РУБЕЖ R", "THRESHOLD R"],
    [" · ЗАКЛЯТИЕ ", " · CURSE "], ["ШАГИ ПО ДОРОГЕ ", "ROAD STEPS "],
    ["Открытая плоскость ", "Open plane "], ["; результат ещё не принят.", "; the result is not yet admitted."],
    ["ПРОБИТИЕ ", "BREACH "], ["ЖИЗНЬ ", "LIFE "], ["РАНГ r", "RANK r"],
    [" · УРОН ПОЛУЧЕН ", " · DAMAGE TAKEN "], ["резерв ", "reserve "], ["нагрузка ", "load "],
    ["Снять руну ", "Remove rune "], [" из узла ", " from node "], ["Пустой узел ", "Empty node "],
    ["; сила ", "; force "], [", связность ", ", coherence "], [", резонанс ", ", resonance "],
  ];
  let translated = core;
  for (const [ru, en] of fragments) translated = translated.replaceAll(ru, en);
  return `${before}${translated}${after}`;
}

function translateValue(locale: Locale, value: unknown): unknown {
  if (typeof value === "string") return translateText(locale, value);
  if (Array.isArray(value)) return value.map((entry) => translateValue(locale, entry));
  if (!value || typeof value !== "object" || isValidElement(value)) return value;
  const prototype = Object.getPrototypeOf(value);
  if (prototype !== Object.prototype && prototype !== null) return value;
  return Object.fromEntries(Object.entries(value).map(([key, entry]) => [key, translateValue(locale, entry)]));
}

const TRANSLATED_ATTRIBUTES = new Set(["aria-label", "alt", "placeholder", "title"]);

function translateNode(locale: Locale, node: ReactNode): ReactNode {
  if (typeof node === "string") return translateText(locale, node);
  if (Array.isArray(node)) return node.map((entry) => translateNode(locale, entry));
  if (!isValidElement(node)) return node;

  const element = node as ReactElement<Record<string, unknown>>;
  const nextProps: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(element.props)) {
    if (key === "children") continue;
    if (TRANSLATED_ATTRIBUTES.has(key) && typeof value === "string") nextProps[key] = translateText(locale, value);
    else if (typeof element.type !== "string") nextProps[key] = translateValue(locale, value);
  }
  const children = Children.map(element.props.children as ReactNode, (child) => translateNode(locale, child));
  return cloneElement(element, nextProps, children);
}

export function LocalizedTree({ locale, children }: { locale: Locale; children: ReactNode }) {
  return <>{translateNode(locale, children)}</>;
}
